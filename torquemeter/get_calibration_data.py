from labjack import ljm
import time
import csv
import os
import statistics

# ==========================================
# USER CONFIGURATION (ADJUST THESE)
# ==========================================

# 1. PHYSICAL CONSTANTS
# ---------------------
# Distance from CENTER OF SENSOR SHAFT to CENTER OF SCALE PLATFORM.
LEVER_ARM_METERS = 0.045847 

# Standard Gravity (m/s^2)
GRAVITY = 9.81

# 2. LABJACK CONFIGURATION
# ------------------------
# We use AIN1 in Single-Ended Mode (Negative Channel 199 = GND).
TARGET_CHANNEL = "AIN1"
NEGATIVE_CH_INDEX = 199 
INPUT_RANGE = 10.0 

# 3. FILE OUTPUT
# --------------
FILENAME = "calibrationDataSlope.csv"

# ==========================================

def GetVoltageAverage(handle, channel, samples=400):
    """
    Reads the sensor multiple times and returns the average to reduce noise.
    """
    readings = []
    for _ in range(samples):
        readings.append(ljm.eReadName(handle, channel))
        # No sleep needed here, we want to burst read to average out noise
    return statistics.mean(readings)

def AnalyzeNoise(handle, channel, samples=500):
    """
    Takes a large burst of samples to characterize the noise.
    Returns (mean, max_fluctuation).
    """
    print(f"   [Noise Check] Taking {samples} samples...", end="", flush=True)
    readings = []
    for _ in range(samples):
        readings.append(ljm.eReadName(handle, channel))
    
    avg = statistics.mean(readings)
    spread = max(readings) - min(readings)
    print(f" Done. Avg: {avg:.5f} V | Spread: {spread:.5f} V")
    return avg

def CalculateAddedTorque(massG):
    """
    Calculates the DELTA torque generated by the added mass.
    Note: This does NOT include the torque from the arm itself.
    """
    massKg = massG / 1000.0
    forceN = massKg * GRAVITY
    torqueNm = forceN * LEVER_ARM_METERS
    return torqueNm

def Main():
    print("\n" + "="*50)
    print("   ECE 506 TORQUE SENSOR CALIBRATION")
    print("   Method: Dead Weight / Slope Calculation")
    print("   Signal: Amplified +/- 5V")
    print("="*50 + "\n")

    # 1. CONNECT TO LABJACK
    try:
        handle = ljm.openS("T7", "ANY", "ANY")
        info = ljm.getHandleInfo(handle)
        print(f" >> Connected to LabJack T7 (Serial: {info[2]})")
    except ljm.LJMError:
        print(" !! ERROR: Could not connect to T7. Check USB.")
        return

    # 2. CONFIGURE AIN1
    try:
        # Set Negative Channel to GND (199)
        ljm.eWriteName(handle, f"{TARGET_CHANNEL}_NEGATIVE_CH", NEGATIVE_CH_INDEX)
        # Set Range to +/- 10.0V (Standard Gain)
        ljm.eWriteName(handle, f"{TARGET_CHANNEL}_RANGE", INPUT_RANGE)
        # Set Resolution Index to 12 (High precision)
        ljm.eWriteName(handle, f"{TARGET_CHANNEL}_RESOLUTION_INDEX", 12)
        print(f" >> Configured {TARGET_CHANNEL} for Single-Ended +/- {INPUT_RANGE}V Range.")
    except Exception as e:
        print(f" !! Config Error: {e}")
        ljm.close(handle)
        return

    # 3. READ FIXTURE BASELINE (With Noise Analysis)
    print("\nReading 'Resting Voltage' (Fixture attached, Scale Empty)...")
    restingVoltage = AnalyzeNoise(handle, TARGET_CHANNEL, samples=1000)
    
    print(f" >> Resting Baseline Established: {restingVoltage:.6f} V")
    print("    (This is your Zero reference for this session)")

    # 4. PREPARE CSV
    fileExists = os.path.isfile(FILENAME)
    with open(FILENAME, mode='a', newline='') as file:
        writer = csv.writer(file)
        if not fileExists:
            writer.writerow([
                "Timestamp", 
                "Added_Mass_g", 
                "Sensor_Voltage_V", 
                "Added_Torque_Nm", 
                "Lever_Arm_m", 
                "Resting_Voltage_V"
            ])
            print(f" >> Created new file: {FILENAME}")
        else:
            print(f" >> Appending to: {FILENAME}")

    print("\n" + "-"*50)
    print("READY TO LOG DATA")
    print("Instructions:")
    print("1. Place a weight on the scale center.")
    print("2. Type the mass in GRAMS (e.g., 10.01) and hit Enter.")
    print("3. Type 'q' to finish.")
    print("-"*50)

    # 5. MAIN LOOP
    try:
        while True:
            # Live View (using 400 samples avg)
            currVolts = GetVoltageAverage(handle, TARGET_CHANNEL, samples=400)
            deltaV = currVolts - restingVoltage
            
            print(f"\rLive: {currVolts:.5f} V (Change: {deltaV:+.5f} V) | Input Mass (g): ", end="")
            
            userInput = input()
            if userInput.lower() == 'q':
                break
            
            try:
                massG = float(userInput)
                
                # Calculate the added torque
                addedTorque = CalculateAddedTorque(massG)
                
                # Capture a high-quality averaged reading for the log (500 samples)
                print("   Capturing stable reading...", end="")
                logVoltage = GetVoltageAverage(handle, TARGET_CHANNEL, samples=500)
                print(" Done.")
                
                timestamp = time.strftime("%Y-%m-%d %H:%M:%S")

                # Write to CSV
                with open(FILENAME, mode='a', newline='') as file:
                    writer = csv.writer(file)
                    writer.writerow([
                        timestamp, 
                        massG, 
                        logVoltage, 
                        addedTorque, 
                        LEVER_ARM_METERS, 
                        restingVoltage
                    ])
                
                print(f"   [SAVED] Added {massG}g (+{addedTorque:.4f} Nm) -> {logVoltage:.6f} V")

            except ValueError:
                print("   Invalid input. Enter a number.")

    except KeyboardInterrupt:
        print("\nStopped by user.")
    finally:
        ljm.close(handle)
        print("\nLabJack Disconnected.")

if __name__ == "__main__":
    Main()
